/** File the scripts write the statusline JSON to, inside the usage folder. */
export const USAGE_RAW_FILE = 'usage-raw.json'

export const POSIX_SCRIPT_FILE = 'statusline.sh'
export const WINDOWS_SCRIPT_FILE = 'statusline.ps1'
export const SCRIPT_FILES = [POSIX_SCRIPT_FILE, WINDOWS_SCRIPT_FILE]
/** The account's own statusline, chained by the script. */
export const ORIGINAL_FILE = 'statusline-original.json'

